import { useEffect, useRef, useState } from 'react';
import { api, type Health } from '../api';
import type { ScenarioView } from '../types';

const NAMES: Record<string, string> = {
  'demo-match': 'Demo match',
  balanced: 'Balanced',
  'possession-illusion': 'Possession illusion',
  'pressing-shift': 'Pressing shift',
};

/** Pick a scripted match and how to play it. Shown in place of the pitch before the first match. */
export function NewMatch({ onStarted, onCancel }: { onStarted: () => void; onCancel?: () => void }) {
  const [scenarios, setScenarios] = useState<ScenarioView[]>([]);
  const [health, setHealth] = useState<Health>();
  const [scenarioId, setScenarioId] = useState('demo-match');
  const [speed, setSpeed] = useState(10);
  const [startMinute, setStartMinute] = useState(0);
  const [offline, setOffline] = useState(false);
  const [holds, setHolds] = useState(true);
  const [error, setError] = useState<string>();
  const [busy, setBusy] = useState(false);
  const first = useRef<HTMLInputElement>(null);

  useEffect(() => {
    api.scenarios().then(setScenarios).catch((e: Error) => setError(e.message));
    api.health().then((h) => { setHealth(h); if (!h.live) setOffline(true); }).catch(() => undefined);
  }, []);
  useEffect(() => { first.current?.focus(); }, [scenarios.length]);

  const start = async () => {
    setBusy(true);
    setError(undefined);
    try {
      await api.start({ scenarioId, speed, startMinute, offline, includeMilestones: true, presentationHolds: holds });
      onStarted();
    } catch (e) {
      setError(`Could not start the match: ${(e as Error).message}`);
    } finally {
      setBusy(false);
    }
  };

  return (
    <form className="new-match" onSubmit={(e) => { e.preventDefault(); void start(); }}>
      <h2>Kick off a match</h2>
      <p className="lede">
        Every match is generated by Match Forge: fictional clubs and players, football-realistic events, scripted
        moments and known ground truth, so the accuracy view can score Second Ball IQ.
      </p>

      <fieldset>
        <legend>Generated match</legend>
        {scenarios.map((s, i) => (
          <label key={s.id} className="choice">
            <input ref={i === 0 ? first : undefined} type="radio" name="scenario" value={s.id}
              checked={scenarioId === s.id} onChange={() => setScenarioId(s.id)} />
            <span>
              <strong>{NAMES[s.id] ?? s.id}</strong>
              <span className="muted">{s.description}</span>
            </span>
          </label>
        ))}
      </fieldset>


      <div className="row">
        <label className="field">
          <span>Speed</span>
          <select value={speed} onChange={(e) => setSpeed(Number(e.target.value))}>
            <option value={1}>Real time</option>
            <option value={5}>5× (18 minutes)</option>
            <option value={10}>10× (9 minutes)</option>
            <option value={30}>30× (3 minutes)</option>
          </select>
        </label>
        <label className="field">
          <span>Start at minute</span>
          <input type="number" min={0} max={90} value={startMinute}
            onChange={(e) => setStartMinute(Math.max(0, Math.min(90, Number(e.target.value) || 0)))} />
        </label>
      </div>

      <label className="check">
        <input type="checkbox" checked={offline} disabled={health ? !health.live : false}
          onChange={(e) => setOffline(e.target.checked)} />
        <span>
          Offline: templates instead of models, gates skipped
          {health && !health.live && <span className="muted"> (the server has no Foundry settings)</span>}
        </span>
      </label>

      <label className="check">
        <input type="checkbox" checked={holds} onChange={(e) => setHolds(e.target.checked)} />
        <span>
          Presentation pause before set pieces
          <span className="muted"> (the replay waits up to 4 s for the prediction, then 2.5 s to read it; off: nothing waits for a model)</span>
        </span>
      </label>

      {error && <p className="problems" role="alert">{error}</p>}
      <div className="qi-actions">
        <button type="submit" className="primary" disabled={busy || scenarios.length === 0}>
          {busy ? 'Starting…' : 'Start match'}
        </button>
        {onCancel && <button type="button" onClick={onCancel}>Cancel</button>}
      </div>
    </form>
  );
}
